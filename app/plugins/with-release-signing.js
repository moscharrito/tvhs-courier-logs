/* Sign a release build with the upload key, not the debug one.
 *
 * ─────────────────────────────────────────────────────────────────────────
 * WHAT THIS FIXES.
 *
 * The template Expo generates ships this, and says so in a comment it
 * expects somebody to read:
 *
 *     release {
 *         // Caution! In production, you need to generate your own keystore
 *         signingConfig signingConfigs.debug
 *     }
 *
 * A release AAB built that way is signed with the debug certificate that
 * ships inside every React Native project. Google Play refuses it outright
 * -- "You uploaded an APK signed with a debug certificate" -- and the only
 * way to find out is to build for fifty minutes, upload, and be told.
 *
 * ─────────────────────────────────────────────────────────────────────────
 * WHY A CONFIG PLUGIN AND NOT AN EDIT.
 *
 * `android/` is gitignored and regenerated by `expo prebuild`. Editing
 * build.gradle there works until the next person regenerates, and then the
 * build quietly goes back to signing with the debug key -- the same silent
 * reversion, with the same fifty-minute feedback loop.
 *
 * ─────────────────────────────────────────────────────────────────────────
 * THE KEY ITSELF NEVER COMES NEAR THIS REPOSITORY.
 *
 * The four values are read from gradle.properties, which the Expo template
 * gitignores, and the keystore lives outside the project entirely. When they
 * are absent -- a debug build, a fresh clone, CI that has no business
 * signing anything -- the release type falls back to the debug config
 * exactly as before, so nothing breaks; it simply cannot produce something
 * Play will take.
 *
 *     IZY_UPLOAD_STORE_FILE=C:/keys/izy-upload.jks
 *     IZY_UPLOAD_KEY_ALIAS=izy-upload
 *     IZY_UPLOAD_STORE_PASSWORD=...
 *     IZY_UPLOAD_KEY_PASSWORD=...
 *
 * THAT KEY IS THE APP. Lose it and the listing can never be updated again:
 * a new key is a new app, with a new install base. It belongs in a password
 * manager or a safe, not only on the laptop that made it.
 */

const { withAppBuildGradle } = require('expo/config-plugins');

const SIGNING_CONFIG = `
        release {
            // Injected by plugins/with-release-signing.js. Absent properties
            // mean an unsigned-for-Play build rather than a broken one.
            if (project.hasProperty('IZY_UPLOAD_STORE_FILE')) {
                storeFile file(IZY_UPLOAD_STORE_FILE)
                storePassword IZY_UPLOAD_STORE_PASSWORD
                keyAlias IZY_UPLOAD_KEY_ALIAS
                keyPassword IZY_UPLOAD_KEY_PASSWORD
            }
        }`;

/** The template's own line, which this replaces. */
const TEMPLATE_RELEASE_SIGNING = 'signingConfig signingConfigs.debug';

module.exports = function withReleaseSigning(config) {
    return withAppBuildGradle(config, (cfg) => {
        let gradle = cfg.modResults.contents;

        if (gradle.includes('IZY_UPLOAD_STORE_FILE')) return cfg;

        /* Add the release signing config beside the debug one. Anchored on
           the debug block's closing brace rather than on a line number,
           because the template moves between Expo versions. */
        const anchor = `        debug {
            storeFile file('debug.keystore')
            storePassword 'android'
            keyAlias 'androiddebugkey'
            keyPassword 'android'
        }`;
        if (!gradle.includes(anchor)) {
            throw new Error(
                'with-release-signing: the debug signingConfig block is not where this expected it. '
                + 'The Expo template has changed; update the anchor rather than letting a release '
                + 'build go out signed with the debug key.',
            );
        }
        gradle = gradle.replace(anchor, anchor + SIGNING_CONFIG);

        /* Point the release build type at it. There are two occurrences of
           the template line -- debug and release -- and only the second is
           inside buildTypes.release, so this replaces the LAST one. */
        const last = gradle.lastIndexOf(TEMPLATE_RELEASE_SIGNING);
        if (last === -1) {
            throw new Error('with-release-signing: no release signingConfig line to replace.');
        }
        gradle = gradle.slice(0, last)
            + 'signingConfig project.hasProperty(\'IZY_UPLOAD_STORE_FILE\') ? signingConfigs.release : signingConfigs.debug'
            + gradle.slice(last + TEMPLATE_RELEASE_SIGNING.length);

        cfg.modResults.contents = gradle;
        return cfg;
    });
};
